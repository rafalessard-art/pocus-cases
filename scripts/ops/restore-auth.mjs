#!/usr/bin/env node
/**
 * Part of scripts/ops/restore-test.sh — authentication recovery in the DISPOSABLE stack.
 *
 * 1. Restores only the sign-in tables that identify people (auth.users, auth.identities,
 *    auth.mfa_factors) and the stored-file records (storage.buckets, storage.objects), table by
 *    table, from the backup's data dumps. Service-managed tables (migration history) and
 *    short-lived ones (sessions, refresh tokens, one-time tokens, challenges, flow state, audit
 *    entries) are deliberately skipped: they belong to the running service, and restoring them
 *    collides with the new stack's own rows. People simply sign in again.
 * 2. With AUTH_MODE=fallback, the sign-in tables are NOT restored; instead every portal profile
 *    gets a fresh account with the SAME id and email (the documented fallback procedure).
 * 3. Verifies every portal profile: an account with the same id exists, it can sign in (one-time
 *    link generated by the admin API, never emailed), and the portal resolves it to the same role.
 *
 * Output: AUTH-RECOVERY.txt or AUTH-FALLBACK.txt (counts, table names and pass/fail only — no emails, ids or values).
 */
import pg from 'pg';
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const { BK, OUT, T_DB, T_API, T_KEY, T_ANON, CONTAINER, AUTH_MODE = 'restore' } = process.env;
if (CONTAINER !== 'supabase_db_pocus-restore-test') throw new Error('not the disposable container');
if (!/^http:\/\/127\.0\.0\.1:55321$/.test(T_API ?? '')) throw new Error('not the disposable stack');
if (!/@127\.0\.0\.1:55322\//.test(T_DB ?? '')) throw new Error('not the disposable database');

const RESTORE = ['auth.users', 'auth.identities', 'auth.mfa_factors', 'storage.buckets', 'storage.objects'];
const AUTH_ONLY = new Set(['auth.users', 'auth.identities', 'auth.mfa_factors']);
const lines = [];
const say = (s) => lines.push(s);

/** Split a pg_dump data file into per-table chunks (INSERT statements or COPY blocks). */
function chunks(text) {
  const out = new Map();
  const add = (t, s) => out.set(t, (out.get(t) ?? '') + s + '\n');
  let i = 0;
  while (i < text.length) {
    // skip blank lines and comments between statements
    if (text[i] === '\n' || text[i] === ' ' || text[i] === '\t' || text[i] === '\r') { i += 1; continue; }
    if (text.startsWith('--', i)) { const e = text.indexOf('\n', i); i = e < 0 ? text.length : e + 1; continue; }
    const head = text.slice(i, i + 300);
    const copy = head.match(/^COPY\s+"?(\w+)"?\."?(\w+)"?\s[^\n]*FROM stdin;\n/i);
    if (copy) {
      const end = text.indexOf('\n\\.\n', i);
      const stop = end < 0 ? text.length : end + 4;
      add(`${copy[1]}.${copy[2]}`, text.slice(i, stop));
      i = stop;
      continue;
    }
    // a statement: read to the ';' that ends it, outside single quotes
    let j = i, q = false;
    for (; j < text.length; j += 1) {
      const c = text[j];
      if (c === "'") q = !q; // '' inside a string toggles twice
      else if (c === ';' && !q) break;
    }
    const stmt = text.slice(i, j + 1);
    const ins = stmt.match(/^INSERT\s+INTO\s+"?(\w+)"?\."?(\w+)"?/i);
    if (ins) add(`${ins[1]}.${ins[2]}`, stmt);
    else add('(other)', stmt);
    i = j + 1;
  }
  return out;
}

function rows(chunk) {
  if (/^COPY/i.test(chunk)) return Math.max(0, chunk.split('\n').length - 3);
  return (chunk.match(/^INSERT\s+INTO/gim) ?? []).length;
}

/** Run SQL in the disposable database container; return a value-free error summary. */
function psql(sql, table) {
  const clear = table ? `DELETE FROM ${table.split('.').map((x) => `"${x}"`).join('.')};\n` : '';
  const r = spawnSync('docker', ['exec', '-i', CONTAINER, 'psql', '-U', 'supabase_admin', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-q'],
    { input: `SET session_replication_role = replica;\nBEGIN;\n${clear}${sql}\nCOMMIT;\n`, encoding: 'utf8', maxBuffer: 1 << 28 });
  if (r.status === 0) return null;
  const err = (r.stderr || '').split('\n').find((l) => /ERROR:/.test(l)) ?? 'unknown error';
  return err.replace(/^.*ERROR:\s*/, '').replace(/'[^']*'/g, "'…'").replace(/\([^)]*\)=\([^)]*\)/g, '(…)=(…)').slice(0, 160);
}

const manifest = JSON.parse(readFileSync(join(BK, 'MANIFEST.json'), 'utf8'));
const files = ['auth-data.sql', 'storage-data.sql', 'auth-storage-data.sql'].map((f) => join(BK, f)).filter(existsSync);
const all = new Map();
for (const f of files) for (const [t, s] of chunks(readFileSync(f, 'utf8'))) all.set(t, (all.get(t) ?? '') + s);

say(`Authentication recovery (${AUTH_MODE === 'fallback' ? 'FALLBACK procedure: new accounts with the same ids' : 'restore of sign-in tables'})`);
const restored = {}, failed = {};
const FALLBACK = AUTH_MODE === 'fallback';
if (FALLBACK) {
  // Drill: behave as if the sign-in tables could not be restored at all.
  const err = psql('DELETE FROM auth.mfa_factors; DELETE FROM auth.identities; DELETE FROM auth.users;');
  if (err) throw new Error(`could not clear the disposable sign-in tables: ${err}`);
  say('  sign-in tables emptied in the disposable stack to rehearse the fallback');
}
for (const t of FALLBACK ? [] : RESTORE) {
  const c = all.get(t);
  if (!c) { say(`  ${t}: no rows in the backup`); continue; }
  const err = psql(c, t);
  if (err) { failed[t] = err; say(`  ${t}: FAILED — ${err}`); continue; }
  const got = Number(spawnSync('docker', ['exec', CONTAINER, 'psql', '-U', 'supabase_admin', '-d', 'postgres', '-tAc', `select count(*) from ${t}`], { encoding: 'utf8' }).stdout.trim());
  const want = manifest.counts?.[t];
  restored[t] = got;
  if (want !== undefined && got !== want) { failed[t] = `row count ${got}, backup ${want}`; say(`  ${t}: FAILED — restored ${got} row(s), backup has ${want}`); }
  else say(`  ${t}: restored ${got} row(s)${want !== undefined ? ' (matches the backup)' : ''}`);
}
const skipped = FALLBACK ? [] : [...all.keys()].filter((t) => t !== '(other)' && !RESTORE.includes(t) && rows(all.get(t)) > 0);
if (skipped.length) say(`  skipped on purpose (service-managed or short-lived): ${skipped.map((t) => `${t} (${rows(all.get(t))})`).join(', ')}`);

const db = new pg.Client({ connectionString: T_DB });
await db.connect();
try {
  // Fallback procedure (and safety net): any portal profile without an account gets one with the same id.
  const missing = (await db.query(`select p.id, p.email from public.profiles p left join auth.users u on u.id = p.id where u.id is null`)).rows;
  let recreated = 0;
  for (const m of missing) {
    await db.query(`insert into auth.users (id, instance_id, aud, role, email, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                      confirmation_token, recovery_token, email_change_token_new, email_change, email_change_token_current, phone_change, phone_change_token, reauthentication_token)
                    values ($1, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', $2, now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(),
                      '', '', '', '', '', '', '', '')`, [m.id, m.email]);
    await db.query(`insert into auth.identities (id, user_id, provider_id, provider, identity_data, created_at, updated_at, last_sign_in_at)
                    values (gen_random_uuid(), $1, $1::text, 'email', jsonb_build_object('sub', $1::text, 'email', $2::text, 'email_verified', true), now(), now(), now())`, [m.id, m.email])
      .catch(() => {});
    recreated += 1;
  }
  if (missing.length) say(`  accounts recreated with their original id (password and authenticator must be set again): ${recreated}`);

  const profiles = (await db.query(`select p.id, p.email, p.role::text as role from public.profiles p where p.active`)).rows;
  const orphans = (await db.query(`select count(*)::int as n from public.profiles p left join auth.users u on u.id = p.id where u.id is null`)).rows[0].n;
  const factors = (await db.query(`select count(*)::int as n from auth.mfa_factors where status = 'verified'`).catch(() => ({ rows: [{ n: 0 }] }))).rows[0].n;
  let usable = 0, linked = 0;
  const problems = [];
  const headers = { apikey: T_KEY, 'content-type': 'application/json', ...(T_KEY.startsWith('eyJ') ? { Authorization: `Bearer ${T_KEY}` } : {}) };
  for (const p of profiles) {
    const gl = await fetch(`${T_API}/auth/v1/admin/generate_link`, { method: 'POST', headers, body: JSON.stringify({ type: 'magiclink', email: p.email }) });
    const gj = gl.ok ? await gl.json() : null;
    const hashed = gj?.properties?.hashed_token ?? gj?.hashed_token;
    if (!hashed) { problems.push(`sign-in link: HTTP ${gl.status}`); continue; }
    const vr = await fetch(`${T_API}/auth/v1/verify`, { method: 'POST', headers: { apikey: T_ANON, 'content-type': 'application/json' }, body: JSON.stringify({ type: 'magiclink', token_hash: hashed }) });
    const vj = vr.ok ? await vr.json() : null;
    if (!vj?.access_token || vj.user?.id !== p.id) { problems.push(`sign-in: HTTP ${vr.status}${vj?.user && vj.user.id !== p.id ? ' (different account id)' : ''}`); continue; }
    usable += 1;
    const rr = await fetch(`${T_API}/rest/v1/rpc/my_access`, { method: 'POST', headers: { apikey: T_ANON, Authorization: `Bearer ${vj.access_token}`, 'content-type': 'application/json' }, body: '{}' });
    const acc = rr.ok ? await rr.json() : null;
    // profile_role proves the account resolves to its own portal record; an admin still needs the
    // authenticator (aal2) before the role is active, which this check deliberately does not bypass.
    if (acc?.profile_role === p.role) linked += 1; else problems.push(`portal record after sign-in: ${acc?.profile_role ?? 'none'} (expected ${p.role})`);
  }
  say(`  portal profiles: ${profiles.length} · without an account: ${orphans}`);
  say(`  accounts that can sign in: ${usable} of ${profiles.length} · resolving to their own portal record and role: ${linked} of ${profiles.length}`);
  say(`  verified authenticator factors restored: ${factors}${AUTH_MODE === 'fallback' || missing.length ? ' (recreated accounts have none: re-enrol)' : ' (the same authenticator apps keep working)'}`);
  for (const pr of [...new Set(problems)]) say(`  problem: ${pr}`);
  const authTablesOk = AUTH_MODE === 'fallback' || [...AUTH_ONLY].every((t) => !failed[t]);
  const status = usable === profiles.length && linked === profiles.length && orphans === 0
    ? (authTablesOk && !missing.length ? 'PASS — accounts restored with their passwords and authenticators' : 'PASS (fallback) — every account recreated and linked; passwords and authenticators must be set again')
    : 'FAIL — not every portal account can be recovered';
  say(`  authentication recovery: ${status}`);
  const filesOk = !failed['storage.objects'] && !failed['storage.buckets'];
  if (!FALLBACK) say(`  stored-file records (buckets and object rows): ${filesOk ? 'restored' : 'FAILED (the files themselves are re-uploaded and checked separately)'}`);
  if (FALLBACK) lines.push('  (fallback drill only; the result of the real restore is in AUTH-RECOVERY.txt)');
  const tag = FALLBACK ? 'AUTH-FALLBACK' : 'AUTH-RECOVERY';
  writeFileSync(join(OUT, `${tag}.txt`), lines.join('\n') + '\n', { mode: 0o600 });
  writeFileSync(join(OUT, `${tag}.status`), status.startsWith('PASS (fallback)') ? 'fallback' : status.startsWith('PASS') ? 'pass' : 'fail');
  if (!FALLBACK) writeFileSync(join(OUT, 'FILE-RECORDS.status'), filesOk ? 'pass' : 'fail');
} finally {
  await db.end();
}
